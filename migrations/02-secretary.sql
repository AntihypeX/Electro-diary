BEGIN;

CREATE TABLE IF NOT EXISTS public.campuses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (btrim(name) <> '')
);
ALTER TABLE public.stud_groups
    ADD COLUMN IF NOT EXISTS campus_id integer REFERENCES public.campuses(id);
ALTER TABLE public.students
    ADD COLUMN IF NOT EXISTS secretary_version bigint NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS stud_groups_campus_idx ON public.stud_groups(campus_id);
CREATE INDEX IF NOT EXISTS students_group_idx ON public.students(in_group);

COMMENT ON TABLE public.campuses IS 'Учебные корпуса';
COMMENT ON COLUMN public.stud_groups.campus_id IS 'Корпус группы. NULL — пока не указан';
COMMENT ON COLUMN public.students.secretary_version IS 'Версия карточки для защиты от одновременного редактирования';
COMMIT;
